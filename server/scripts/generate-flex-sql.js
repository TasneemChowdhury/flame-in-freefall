const fs = require('fs');
const path = require('path');

const csvPath = path.resolve(__dirname, '../../database/flex_test_runs.csv');
const outSqlPath = path.resolve(__dirname, '../../database/flex_test_runs.sql');

const lines = fs.readFileSync(csvPath, 'utf8').trim().split('\n');

let sql = `-- ============================================================================
-- NASA Space Apps Challenge 2026: Flame in Freefall
-- PSI-69 FLEX (Flame Extinguishment Experiment): 274 Flight Test Runs
-- ============================================================================

BEGIN;

-- 1. Ensure master table columns and PSI-69 parent record exist
CREATE TABLE IF NOT EXISTS public.investigations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nasa_id VARCHAR(100) UNIQUE,
    title VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.investigations
    ADD COLUMN IF NOT EXISTS acronym VARCHAR(100),
    ADD COLUMN IF NOT EXISTS full_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS fire_safety_pillar VARCHAR(50),
    ADD COLUMN IF NOT EXISTS fuel_domain VARCHAR(50),
    ADD COLUMN IF NOT EXISTS hardware_rack VARCHAR(100),
    ADD COLUMN IF NOT EXISTS space_application VARCHAR(100);

INSERT INTO public.investigations (
    nasa_id, acronym, full_name, title, fire_safety_pillar, fuel_domain, hardware_rack, space_application
)
VALUES (
    'PSI-69', 'PSI-69', 'Flame Extinguishment Experiment (FLEX)', 'PSI-69 FLEX',
    'Suppression', 'Liquid', 'CIR / MDCA', 'Lunar Base'
)
ON CONFLICT (nasa_id) DO UPDATE SET
    acronym = EXCLUDED.acronym,
    full_name = EXCLUDED.full_name,
    fire_safety_pillar = EXCLUDED.fire_safety_pillar,
    fuel_domain = EXCLUDED.fuel_domain,
    hardware_rack = EXCLUDED.hardware_rack,
    space_application = EXCLUDED.space_application;

-- 2. Create the FLEX test runs table
DROP TABLE IF EXISTS public.flex_test_runs CASCADE;

CREATE TABLE public.flex_test_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT REFERENCES public.investigations(id) ON DELETE CASCADE,
    test_number INTEGER NOT NULL UNIQUE,
    flex_identifier VARCHAR(50) NOT NULL,
    test_date DATE,
    test_gmt TIME,
    fuel VARCHAR(50) NOT NULL,
    ambient_pressure_mmhg DOUBLE PRECISION,
    ambient_pressure_atm DOUBLE PRECISION,
    o2_mole_fraction DOUBLE PRECISION,
    n2_mole_fraction DOUBLE PRECISION,
    co2_mole_fraction DOUBLE PRECISION,
    he_mole_fraction DOUBLE PRECISION,
    droplet_initial_dia_mm DOUBLE PRECISION,
    visible_extinction_dia_mm DOUBLE PRECISION,
    burning_rate_mm2_s DOUBLE PRECISION,
    burn_time_s DOUBLE PRECISION,
    test_end VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_flex_runs_fuel ON public.flex_test_runs(fuel);
CREATE INDEX IF NOT EXISTS idx_flex_runs_outcome ON public.flex_test_runs(test_end);
CREATE INDEX IF NOT EXISTS idx_flex_runs_pressure ON public.flex_test_runs(ambient_pressure_atm);
CREATE INDEX IF NOT EXISTS idx_flex_runs_identifier ON public.flex_test_runs(flex_identifier);

ALTER TABLE public.flex_test_runs ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'flex_test_runs' AND policyname = 'Allow public select on flex_test_runs') THEN
        CREATE POLICY "Allow public select on flex_test_runs" ON public.flex_test_runs FOR SELECT USING (true);
    END IF;
END $$;

WITH flex_inv AS (
    SELECT id FROM public.investigations WHERE acronym = 'PSI-69' LIMIT 1
)
INSERT INTO public.flex_test_runs (
    investigation_id, test_number, flex_identifier, test_date, test_gmt, fuel,
    ambient_pressure_mmhg, ambient_pressure_atm, o2_mole_fraction, n2_mole_fraction,
    co2_mole_fraction, he_mole_fraction, droplet_initial_dia_mm, visible_extinction_dia_mm,
    burning_rate_mm2_s, burn_time_s, test_end
)
VALUES
`;

const valueRows = [];
for (let i = 1; i < lines.length; i++) {
  const parts = lines[i].split(',');
  const testNum = parseInt(parts[0], 10);
  const identifier = parts[1].trim();
  const dateStr = parts[2].trim();
  const timeStr = parts[3]?.trim();
  const fuel = parts[4].trim();
  const pMmHg = parseFloat(parts[5]);
  const pAtm = !isNaN(pMmHg) && pMmHg > 0 ? (pMmHg / 760).toFixed(4) : 'NULL';
  const o2 = parseFloat(parts[6]);
  const n2 = parseFloat(parts[7]);
  const co2 = parseFloat(parts[8]);
  const he = parseFloat(parts[9]);
  const d0 = parseFloat(parts[10]);
  const dext = parseFloat(parts[11]);
  const k = parseFloat(parts[12]);
  const burnTime = parseFloat(parts[13]?.replace('~', ''));
  const testEnd = parts[14]?.trim() || 'Unknown';

  const dateVal = dateStr ? `'${dateStr}'::DATE` : 'NULL';
  const timeVal = timeStr ? `'${timeStr}'::TIME` : 'NULL';

  valueRows.push(`((SELECT id FROM flex_inv), ${testNum}, '${identifier}', ${dateVal}, ${timeVal}, '${fuel}', ${isNaN(pMmHg) ? 'NULL' : pMmHg}, ${pAtm}, ${isNaN(o2) ? 'NULL' : o2}, ${isNaN(n2) ? 'NULL' : n2}, ${isNaN(co2) ? 'NULL' : co2}, ${isNaN(he) ? 'NULL' : he}, ${isNaN(d0) ? 'NULL' : d0}, ${isNaN(dext) ? 'NULL' : dext}, ${isNaN(k) ? 'NULL' : k}, ${isNaN(burnTime) ? 'NULL' : burnTime}, '${testEnd}')`);
}

sql += valueRows.join(',\n');
sql += `
ON CONFLICT (test_number) DO UPDATE SET
    investigation_id = EXCLUDED.investigation_id,
    flex_identifier = EXCLUDED.flex_identifier,
    test_date = EXCLUDED.test_date,
    test_gmt = EXCLUDED.test_gmt,
    fuel = EXCLUDED.fuel,
    ambient_pressure_mmhg = EXCLUDED.ambient_pressure_mmhg,
    ambient_pressure_atm = EXCLUDED.ambient_pressure_atm,
    o2_mole_fraction = EXCLUDED.o2_mole_fraction,
    n2_mole_fraction = EXCLUDED.n2_mole_fraction,
    co2_mole_fraction = EXCLUDED.co2_mole_fraction,
    he_mole_fraction = EXCLUDED.he_mole_fraction,
    droplet_initial_dia_mm = EXCLUDED.droplet_initial_dia_mm,
    visible_extinction_dia_mm = EXCLUDED.visible_extinction_dia_mm,
    burning_rate_mm2_s = EXCLUDED.burning_rate_mm2_s,
    burn_time_s = EXCLUDED.burn_time_s,
    test_end = EXCLUDED.test_end;

COMMIT;

SELECT
    fuel,
    test_end,
    COUNT(*) AS test_count,
    ROUND(AVG(ambient_pressure_atm)::numeric, 2) AS avg_pressure_atm,
    ROUND(AVG(o2_mole_fraction)::numeric, 3) AS avg_o2,
    ROUND(AVG(droplet_initial_dia_mm)::numeric, 2) AS avg_d0_mm,
    ROUND(AVG(visible_extinction_dia_mm)::numeric, 2) AS avg_ext_dia_mm,
    ROUND(AVG(burning_rate_mm2_s)::numeric, 2) AS avg_k
FROM public.flex_test_runs
GROUP BY fuel, test_end
ORDER BY fuel, test_end;
`;

fs.writeFileSync(outSqlPath, sql);
console.log('Regenerated self-contained database/flex_test_runs.sql');

-- 1. Master Investigations Table
CREATE TABLE IF NOT EXISTS public.investigations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nasa_id VARCHAR(100) UNIQUE,
    acronym VARCHAR(100) UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    research_question TEXT,

    fire_safety_pillar VARCHAR(50) NOT NULL DEFAULT 'Prevention', -- 'Prevention', 'Detection', 'Suppression'
    fuel_domain VARCHAR(50) NOT NULL DEFAULT 'Solid',            -- 'Solid', 'Liquid', 'Gaseous', 'Aerosol'
    hardware_rack VARCHAR(100),                                   -- 'CIR', 'MSG', 'CIR / MDCA', 'Cygnus Flow Duct'
    space_application VARCHAR(100),                               -- 'Lunar Base', 'Mars Transit', 'Spacesuit'
    relevance_score INTEGER DEFAULT 90,

    facility VARCHAR(255),
    platform VARCHAR(255),
    start_date DATE,
    end_date DATE,
    source_url VARCHAR(2048),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Ensure backwards-compatible columns if table already existed
ALTER TABLE public.investigations
    ADD COLUMN IF NOT EXISTS acronym VARCHAR(100),
    ADD COLUMN IF NOT EXISTS full_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS fire_safety_pillar VARCHAR(50),
    ADD COLUMN IF NOT EXISTS fuel_domain VARCHAR(50),
    ADD COLUMN IF NOT EXISTS hardware_rack VARCHAR(100),
    ADD COLUMN IF NOT EXISTS space_application VARCHAR(100),
    ADD COLUMN IF NOT EXISTS research_question TEXT,
    ADD COLUMN IF NOT EXISTS relevance_score INTEGER DEFAULT 90;

-- 2. Flexible Numerical Range Parameters (for cross-experiment matrix)
CREATE TABLE IF NOT EXISTS public.investigation_parameters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT NOT NULL,
    parameter_name VARCHAR(100) NOT NULL,
    min_value DOUBLE PRECISION NOT NULL,
    max_value DOUBLE PRECISION NOT NULL,
    unit VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_investigation_params_investigation
        FOREIGN KEY (investigation_id)
        REFERENCES public.investigations(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT uq_investigation_parameter_name
        UNIQUE (investigation_id, parameter_name)
);

-- 3. Investigation AI Insights & Scenario Rankings
CREATE TABLE IF NOT EXISTS public.investigation_ai_insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT NOT NULL,
    scenario_tag VARCHAR(100) NOT NULL,
    comparative_summary TEXT NOT NULL,
    safety_insight TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_investigation_insights_investigation
        FOREIGN KEY (investigation_id)
        REFERENCES public.investigations(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT uq_investigation_scenario_insight
        UNIQUE (investigation_id, scenario_tag)
);

-- 4. Experiments Table (Sample-level details e.g. Saffire-I Sample 1)
CREATE TABLE IF NOT EXISTS public.experiments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT NOT NULL,

    nasa_id VARCHAR(100) UNIQUE,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    experiment_date DATE,
    source_url VARCHAR(2048),
    metadata JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_experiments_investigation
        FOREIGN KEY (investigation_id)
        REFERENCES public.investigations(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Indices for performance
CREATE INDEX IF NOT EXISTS idx_investigations_pillar ON public.investigations (fire_safety_pillar);
CREATE INDEX IF NOT EXISTS idx_investigations_fuel ON public.investigations (fuel_domain);
CREATE INDEX IF NOT EXISTS idx_investigations_app ON public.investigations (space_application);
CREATE INDEX IF NOT EXISTS idx_investigation_params_id ON public.investigation_parameters (investigation_id);
CREATE INDEX IF NOT EXISTS idx_investigation_params_name ON public.investigation_parameters (parameter_name);
CREATE INDEX IF NOT EXISTS idx_investigation_insights_tag ON public.investigation_ai_insights (scenario_tag);
CREATE INDEX IF NOT EXISTS idx_investigation_insights_id ON public.investigation_ai_insights (investigation_id);

-- Automatic updated_at trigger function
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS investigations_set_updated_at ON public.investigations;
CREATE TRIGGER investigations_set_updated_at
    BEFORE UPDATE ON public.investigations
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS experiments_set_updated_at ON public.experiments;
CREATE TRIGGER experiments_set_updated_at
    BEFORE UPDATE ON public.experiments
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

-- Row Level Security (RLS) & Public Read Access
ALTER TABLE public.investigations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.investigation_parameters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.investigation_ai_insights ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.experiments ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'investigations' AND policyname = 'Allow public select on investigations') THEN
        CREATE POLICY "Allow public select on investigations" ON public.investigations FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'investigation_parameters' AND policyname = 'Allow public select on investigation_parameters') THEN
        CREATE POLICY "Allow public select on investigation_parameters" ON public.investigation_parameters FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'investigation_ai_insights' AND policyname = 'Allow public select on investigation_ai_insights') THEN
        CREATE POLICY "Allow public select on investigation_ai_insights" ON public.investigation_ai_insights FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'experiments' AND policyname = 'Allow public select on experiments') THEN
        CREATE POLICY "Allow public select on experiments" ON public.experiments FOR SELECT USING (true);
    END IF;
END $$;

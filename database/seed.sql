-- Verification query
SELECT
    i.acronym,
    i.full_name,
    i.fire_safety_pillar,
    i.fuel_domain,
    COUNT(DISTINCT p.id) AS parameter_count,
    COUNT(DISTINCT a.id) AS insight_count
FROM public.investigations i
LEFT JOIN public.investigation_parameters p ON p.investigation_id = i.id
LEFT JOIN public.investigation_ai_insights a ON a.investigation_id = i.id
WHERE i.acronym IN ('PSI-69', 'PSI-68', 'BASS', 'Saffire-I', 'CFI-G')
GROUP BY i.id, i.acronym, i.full_name, i.fire_safety_pillar, i.fuel_domain
ORDER BY i.acronym;

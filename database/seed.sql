-- 2. Create flexible parameters and AI insights tables if they do not exist
CREATE TABLE IF NOT EXISTS public.investigation_parameters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT NOT NULL,
    parameter_name VARCHAR(100) NOT NULL,
    min_value DOUBLE PRECISION NOT NULL,
    max_value DOUBLE PRECISION NOT NULL,
    unit VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_investigation_params_investigation
        FOREIGN KEY (investigation_id)
        REFERENCES public.investigations(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT uq_investigation_parameter_name
        UNIQUE (investigation_id, parameter_name)
);

CREATE TABLE IF NOT EXISTS public.investigation_ai_insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT NOT NULL,
    scenario_tag VARCHAR(100) NOT NULL,

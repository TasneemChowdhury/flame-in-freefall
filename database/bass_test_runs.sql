-- ============================================================
-- 4. Convenience view: summary counts by fuel category
-- ============================================================
CREATE OR REPLACE VIEW public.bass_fuel_summary AS
SELECT
    fuel_category,
    COUNT(*)                              AS total_runs,
    COUNT(DISTINCT sample_number)         AS distinct_samples,
    COUNT(DISTINCT fuel_geometry)         AS geometry_variants,
    MIN(run_date)                         AS first_run,
    MAX(run_date)                         AS last_run
FROM public.bass_test_runs
GROUP BY fuel_category
ORDER BY total_runs DESC;


CREATE TABLE IF NOT EXISTS public.sensor_readings (
    reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NULL,
    sample_number SMALLINT NOT NULL CHECK (sample_number BETWEEN 0 AND 255),
    source_file VARCHAR(255) NOT NULL,
    record_index INTEGER NOT NULL CHECK (record_index >= 0),
    elapsed_time_s DOUBLE PRECISION NOT NULL,
    epoch_time_ms BIGINT NOT NULL CHECK (epoch_time_ms >= 0),
    fan_speed_rpm DOUBLE PRECISION,
    co2_percent DOUBLE PRECISION,
    o2_percent DOUBLE PRECISION,
    anemometer_1_cm_s DOUBLE PRECISION,
    anemometer_2_cm_s DOUBLE PRECISION,
    ambient_pressure_psia DOUBLE PRECISION,
    radiometer_1_mw_cm2 DOUBLE PRECISION,
    radiometer_2_mw_cm2 DOUBLE PRECISION,
    radiometer_3_mw_cm2 DOUBLE PRECISION,
    radiometer_4_mw_cm2 DOUBLE PRECISION,
    downstream_front_mw_cm2 DOUBLE PRECISION,
    upstream_front_mw_cm2 DOUBLE PRECISION,
    upstream_back_mw_cm2 DOUBLE PRECISION,
    downstream_back_mw_cm2 DOUBLE PRECISION,
    humidity_percent DOUBLE PRECISION,
    test_section_inlet_temp_c DOUBLE PRECISION,
    plume_temp_1_c DOUBLE PRECISION,
    plume_temp_2_c DOUBLE PRECISION,
    plume_temp_3_c DOUBLE PRECISION,
    plume_temp_4_c DOUBLE PRECISION,
    plume_temp_5_c DOUBLE PRECISION,
    plume_temp_6_c DOUBLE PRECISION,
    sample_temp_1_c DOUBLE PRECISION,
    sample_temp_2_c DOUBLE PRECISION,
    sample_temp_3_c DOUBLE PRECISION,
    sample_temp_4_c DOUBLE PRECISION,
    sample_temp_5_c DOUBLE PRECISION,
    sample_temp_6_c DOUBLE PRECISION,
    igniter_current_a DOUBLE PRECISION,
    igniter_voltage_v DOUBLE PRECISION,
    igniter_power_enable DOUBLE PRECISION,

    CONSTRAINT uq_sensor_readings_source_record
        UNIQUE (source_file, record_index),
    CONSTRAINT fk_sensor_readings_experiment
        FOREIGN KEY (experiment_id)
        REFERENCES public.experiments(id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sensor_readings_experiment_time
    ON public.sensor_readings (experiment_id, elapsed_time_s);

ALTER TABLE public.sensor_readings ENABLE ROW LEVEL SECURITY;

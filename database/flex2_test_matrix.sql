-- 2. Create the FLEX-2 experimental matrix table
DROP TABLE IF EXISTS public.flex2_test_matrix CASCADE;

CREATE TABLE public.flex2_test_matrix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT REFERENCES public.investigations(id) ON DELETE CASCADE,
    sample_name VARCHAR(100) NOT NULL UNIQUE,
    fuel_category VARCHAR(50) NOT NULL,
    droplet_min_dia_mm DOUBLE PRECISION NOT NULL DEFAULT 1.5,
    droplet_max_dia_mm DOUBLE PRECISION NOT NULL DEFAULT 5.0,
    ambient_gas_mixture VARCHAR(100) NOT NULL,
    o2_mole_fractions DOUBLE PRECISION[] NOT NULL,
    o2_min_fraction DOUBLE PRECISION NOT NULL DEFAULT 0.17,
    o2_max_fraction DOUBLE PRECISION NOT NULL DEFAULT 0.30,
    ambient_pressures_atm DOUBLE PRECISION[] NOT NULL,
    pressure_min_atm DOUBLE PRECISION NOT NULL DEFAULT 0.50,
    pressure_max_atm DOUBLE PRECISION NOT NULL DEFAULT 3.00,
    ambient_temperature_c DOUBLE PRECISION NOT NULL DEFAULT 25.0,
    flow_velocity_min_cm_s DOUBLE PRECISION NOT NULL DEFAULT 0.10,
    flow_velocity_max_cm_s DOUBLE PRECISION NOT NULL DEFAULT 5.00,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_flex2_category ON public.flex2_test_matrix(fuel_category);

ALTER TABLE public.flex2_test_matrix ENABLE ROW LEVEL SECURITY;

